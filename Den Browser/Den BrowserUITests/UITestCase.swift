import AppKit
import Carbon.HIToolbox
import XCTest

class UITestCase: XCTestCase, BDD {
    private var previousInputSource: TISInputSource?
    private var processLock: UITestProcessLock?
    private var defaultsSuiteNames: [String] = []
    var fixtureDirectories: [URL] = []

    override func setUpWithError() throws {
        processLock = try UITestProcessLock()
        continueAfterFailure = false
        // Keep synthetic text input on Apple's ABC layout; restore user's IME in tearDown.
        if let current = TISCopyCurrentKeyboardInputSource()?.takeRetainedValue() {
            previousInputSource = current
        }
        let abcID = "com.apple.keylayout.ABC"
        try selectInputSource(id: abcID)
        XCTAssertTrue(waitForInputSource(id: abcID), "Timed out waiting for input source \(abcID)")
    }

    override func tearDownWithError() throws {
        MainActor.assumeIsolated {
            uiTestApplication().terminate()
        }
        if let previousInputSource {
            selectInputSource(previousInputSource)
            if let targetID = inputSourceID(for: previousInputSource) {
                waitForInputSource(id: targetID)
            }
        }
        for suiteName in defaultsSuiteNames {
            UserDefaults().removePersistentDomain(forName: suiteName)
        }
        for directory in fixtureDirectories {
            try? FileManager.default.removeItem(at: directory)
        }
        processLock = nil
    }

    private func inputSourceID(for source: TISInputSource) -> String? {
        guard let ptr = TISGetInputSourceProperty(source, kTISPropertyInputSourceID) else { return nil }
        return Unmanaged<CFString>.fromOpaque(ptr).takeUnretainedValue() as String
    }

    private func currentInputSourceID() -> String? {
        guard let source = TISCopyCurrentKeyboardInputSource()?.takeRetainedValue() else { return nil }
        return inputSourceID(for: source)
    }

    private func selectInputSource(id: String) throws {
        let properties = [kTISPropertyInputSourceID: id as CFString] as CFDictionary
        let sources = TISCreateInputSourceList(properties, false)?.takeRetainedValue() as Array?
        // Carbon exposes input sources through an untyped CFArray.
        // swiftlint:disable:next force_cast
        let source = try XCTUnwrap(sources?.first as! TISInputSource?)
        selectInputSource(source)
    }

    private func selectInputSource(_ source: TISInputSource) {
        TISSelectInputSource(source)
    }

    @discardableResult
    private func waitForInputSource(id: String, timeout: TimeInterval = 3) -> Bool {
        let deadline = Date().addingTimeInterval(timeout)
        while Date() < deadline {
            if currentInputSourceID() == id { return true }
            Thread.sleep(forTimeInterval: 0.05)
        }
        return currentInputSourceID() == id
    }

    func paste(_ text: String, in app: XCUIApplication) {
        let pasteboard = NSPasteboard.general
        let previousItems: [[NSPasteboard.PasteboardType: Data]] =
            pasteboard.pasteboardItems?.compactMap { item in
                var map: [NSPasteboard.PasteboardType: Data] = [:]
                for type in item.types {
                    if let data = item.data(forType: type) { map[type] = data }
                }
                return map.isEmpty ? nil : map
            } ?? []

        defer {
            pasteboard.clearContents()
            for map in previousItems {
                let restored = NSPasteboardItem()
                for (type, data) in map {
                    restored.setData(data, forType: type)
                }
                pasteboard.writeObjects([restored])
            }
        }

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([item])

        app.typeKey("v", modifierFlags: [.command])
    }

    func makeHTMLFixture(_ html: String) throws -> URL {
        let directory = FileManager.default.temporaryDirectory.appending(path: UUID().uuidString)
        fixtureDirectories.append(directory)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let url = directory.appending(path: "fixture.html")
        try html.write(to: url, atomically: true, encoding: .utf8)
        return url
    }

    @MainActor
    func prepareApp(
        fixture: UITestFixture = .interactionBasics,
        boardCount: UITestBoardCount = .three,
        terminalBoard: Bool = false,
        standardMotion: Bool = false,
        sheetNavigationEnabled: Bool = false,
        multipleDrawerItems: Bool = false,
        drawerSheetURL: URL? = nil,
        recentURL: URL? = nil,
        essentialURL: URL? = nil
    ) -> XCUIApplication {
        let app = uiTestApplication()
        let runID = UUID().uuidString
        let runDirectory = FileManager.default.temporaryDirectory
            .appending(path: "DenBrowserUITests", directoryHint: .isDirectory)
            .appending(path: runID, directoryHint: .isDirectory)
        let seedURL = runDirectory.appending(path: "initial-profile.json")
        fixtureDirectories.append(runDirectory)
        do {
            try FileManager.default.createDirectory(at: runDirectory, withIntermediateDirectories: true)
            try UITestFixtureFactory.makeProfileSeed(
                fixture: fixture,
                boardCount: boardCount,
                terminalBoard: terminalBoard,
                multipleDrawerItems: multipleDrawerItems,
                drawerSheetURL: drawerSheetURL,
                recentURL: recentURL
            )
            .write(to: seedURL, options: .atomic)
        } catch {
            XCTFail("Could not write UI test profile seed: \(error)")
        }
        var args = [
            "-ApplePersistenceIgnoreState", "YES",
            "--ui-testing", "--initial-profile", seedURL.path,
        ]
        if sheetNavigationEnabled {
            args.append("--enable-sheet-navigation")
        }
        args += ["-preferences.appearance.motion.mode", standardMotion ? "standard" : "reduced"]
        if let essentialURL {
            do {
                let data = try UITestFixtureFactory.makeEssentials(url: essentialURL)
                // NSArgumentDomain parses <hex> as Data, matching the stored property-list value.
                let hex = data.map { String(format: "%02x", $0) }.joined()
                args += ["-preferences.essentials.items", "<\(hex)>"]
            } catch {
                XCTFail("Could not encode UI test Essentials: \(error)")
            }
        }
        app.launchArguments = args
        defaultsSuiteNames.append(uiTestDefaultsSuiteName(runID: runID))
        app.launchEnvironment["DEN_UI_TEST_RUN_ID"] = runID
        return app
    }

    @MainActor
    func launchApp(
        fixture: UITestFixture = .interactionBasics,
        boardCount: UITestBoardCount = .three,
        terminalBoard: Bool = false,
        standardMotion: Bool = false,
        sheetNavigationEnabled: Bool = false,
        multipleDrawerItems: Bool = false,
        drawerSheetURL: URL? = nil,
        recentURL: URL? = nil,
        essentialURL: URL? = nil
    ) -> XCUIApplication {
        let app = prepareApp(
            fixture: fixture,
            boardCount: boardCount,
            terminalBoard: terminalBoard,
            standardMotion: standardMotion,
            sheetNavigationEnabled: sheetNavigationEnabled,
            multipleDrawerItems: multipleDrawerItems,
            drawerSheetURL: drawerSheetURL,
            recentURL: recentURL,
            essentialURL: essentialURL
        )
        app.launch()
        // Each fixture has one Profile; invoke its menu action without navigating the menu.
        app.typeKey("u", modifierFlags: [.command, .option, .shift])

        XCTAssertTrue(
            app.children(matching: .window).firstMatch.waitUntilExists(timeout: 10),
            "Application window should appear"
        )
        XCTAssertTrue(board(fixture.initialBoard, in: app).waitUntilExists(timeout: 20))
        if fixture == .interactionBasics {
            if boardCount != .one {
                XCTAssertTrue(board(.bravo, in: app).exists)
            }
            if boardCount == .three {
                XCTAssertTrue(board(.charlie, in: app).exists)
            }
        }
        return app
    }

    @MainActor
    func enterDenMode(in app: XCUIApplication) {
        app.children(matching: .window).firstMatch.typeKey(",", modifierFlags: .control)
        assertDenMode(in: app)
    }

    @MainActor
    func assertDenMode(in app: XCUIApplication) {
        XCTAssertTrue(
            app.children(matching: .window).matching(identifier: "UI Testing · DEN MODE").firstMatch.waitUntilExists(
                timeout: 5
            ),
            "Den should enter Den Mode"
        )
    }

    @MainActor
    func board(_ board: FixtureBoard, in app: XCUIApplication) -> XCUIElement {
        boardHeader(board, in: app)
    }

    @MainActor
    func boardSurface(_ board: FixtureBoard, in app: XCUIApplication) -> XCUIElement {
        app.descendants(matching: .any)
            .matching(identifier: "board-surface.\(board.rawValue)")
            .firstMatch
    }

    @MainActor
    func boardHeader(_ board: FixtureBoard, in app: XCUIApplication) -> XCUIElement {
        app.children(matching: .window).descendants(matching: .any).matching(
            identifier: "board-header.\(board.rawValue)"
        ).firstMatch
    }

    @MainActor
    func overviewBoard(_ board: FixtureBoard, in app: XCUIApplication) -> XCUIElement {
        app.descendants(matching: .any)
            .matching(identifier: "overview-board.\(board.rawValue)")
            .firstMatch
    }

    @MainActor
    func desk(_ desk: FixtureDesk, in app: XCUIApplication) -> XCUIElement {
        app.children(matching: .window).descendants(matching: .any).matching(
            identifier: "desk-switcher.\(desk.rawValue)"
        ).firstMatch
    }

    @MainActor
    func assertEventually(
        _ message: @autoclosure () -> String,
        timeout: TimeInterval = 5,
        file: StaticString = #filePath,
        line: UInt = #line,
        condition: @escaping () -> Bool
    ) {
        if condition() { return }
        let expectation = XCTNSPredicateExpectation(
            predicate: NSPredicate { _, _ in condition() },
            object: nil
        )
        XCTAssertEqual(
            XCTWaiter.wait(for: [expectation], timeout: timeout),
            .completed,
            message(),
            file: file,
            line: line
        )
    }

    @MainActor
    func assertValue(
        _ expected: String,
        in element: XCUIElement,
        file: StaticString = #filePath,
        line: UInt = #line
    ) {
        assertEventually(
            "Expected \(element.identifier) value \(expected.debugDescription), got \(String(describing: element.value))",
            file: file,
            line: line
        ) {
            element.value as? String == expected
        }
    }
}
